  /* ─── Sticky column resize ──────────────────────────────────────────────────
     The whole layout hangs off the `--label-w` custom property emitted by the
     server, so dragging only has to update that one variable: the column, the
     sticky cells, the table width and the "today" band all follow from CSS. */
  var ColumnResize = {
    width: function () { return cssNumber('--label-w', 340); },

    apply: function (width) {
      var min = cssNumber('--label-w-min', 160);
      var max = cssNumber('--label-w-max', 900);
      var clamped = Math.max(min, Math.min(max, Math.round(width)));
      document.documentElement.style.setProperty('--label-w', clamped + 'px');
      return clamped;
    },

    save: function (width) {
      try { localStorage.setItem(LABEL_W_KEY, String(width)); } catch (err) { /* noop */ }
    },

    restore: function () {
      var saved = null;
      try { saved = parseFloat(localStorage.getItem(LABEL_W_KEY)); } catch (err) { saved = null; }
      if (saved && !isNaN(saved)) this.apply(saved);
    },

    init: function () {
      var bar = document.querySelector('.col-resize-handle__bar');
      var self = this;
      if (!bar) return;

      var dragging = false;
      var startX = 0;
      var startWidth = 0;

      bar.addEventListener('mousedown', function (event) {
        dragging = true;
        startX = event.clientX;
        startWidth = self.width();
        bar.classList.add('is-dragging');
        document.body.classList.add('col-resize-active');
        event.preventDefault();
      });

      document.addEventListener('mousemove', function (event) {
        if (!dragging) return;
        self.apply(startWidth + (event.clientX - startX));
      });

      function endDrag() {
        if (!dragging) return;
        dragging = false;
        bar.classList.remove('is-dragging');
        document.body.classList.remove('col-resize-active');
        self.save(self.width());
      }

      document.addEventListener('mouseup', endDrag);
      document.addEventListener('mouseleave', endDrag);

    }
  };

